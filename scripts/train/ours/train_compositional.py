"""Assemble-then-refine compositional training of the whole-brain denoiser.

Starting from the pretrained whole-brain LDM, the denoiser is fine-tuned on
scaffold-injected latents while the autoencoders and part LDMs stay frozen:

  * a training latent is forward-noised to t_inj ~ U[t_inj_min, t_inj_max];
  * the scaffold is built from the denoiser's own clean estimate at t_inj: the
    template crops are regenerated by the frozen part experts from
    t_part = part_t_ratio * t_inj, assembled, re-encoded, and injected;
  * the denoiser predicts the noise of the injected latent; the loss is taken on
    the seam band around the part boundaries with the training scan as target,
    weighted by min(1, 1/SNR_t), and added to the standard denoising loss.

Single GPU:
    python scripts/train/ours/train_compositional.py --config configs/train/ours/whole_brain_compositional_spacing1p5.json
Multi-GPU:
    torchrun --standalone --nproc_per_node=4 scripts/train/ours/train_compositional.py --config ...
"""

