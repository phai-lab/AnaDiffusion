def setup_distributed():
    if "WORLD_SIZE" in os.environ and int(os.environ["WORLD_SIZE"]) > 1:
        dist.init_process_group(backend="nccl")
        local_rank = int(os.environ["LOCAL_RANK"])
        torch.cuda.set_device(local_rank)
        return dist.get_rank(), dist.get_world_size(), torch.device(f"cuda:{local_rank}")
    return 0, 1, torch.device("cuda" if torch.cuda.is_available() else "cpu")


def seed_all(seed: int):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cuda.matmul.allow_tf32 = True
    torch.backends.cudnn.allow_tf32 = True


def broadcast_int(value: int, device: torch.device) -> int:
    if not dist.is_initialized():
        return value
    tensor = torch.tensor([value], device=device, dtype=torch.long)
    dist.broadcast(tensor, src=0)
    return int(tensor.item())


def mean_across_ranks(value: torch.Tensor) -> float:
    value = value.detach().clone()
    if dist.is_initialized():
        dist.all_reduce(value, op=dist.ReduceOp.SUM)
        value /= dist.get_world_size()
    return float(value.item())


def snr_weight(abar_t: torch.Tensor) -> torch.Tensor:
    """min(1, 1/SNR_t): epsilon-space weight for high t, x0-space weight for low t."""
    return torch.clamp((1.0 - abar_t) / abar_t, max=1.0)


def build_models(args, device):
    ae_kwargs = dict(latent_channels=args.ae_latent_ch, num_channels=parse_ints(args.ae_num_channels))
    unet_kwargs = dict(
        latent_channels=args.ae_latent_ch,
        num_channels=parse_ints(args.ldm_num_channels),
        num_head_channels=parse_ints(args.ldm_num_head_channels),
    )
    whole_ae = models.build_autoencoder(**ae_kwargs).to(device)
    whole_unet = models.build_unet(**unet_kwargs).to(device)
    hemi_ae = models.build_autoencoder(**ae_kwargs).to(device)
    hemi_unet = models.build_unet(cross_attention_dim=args.hemi_cond_dim, **unet_kwargs).to(device)
    hemi_conditioner = models.HemisphereConditioner(n_parts=2, d_model=args.hemi_cond_dim).to(device)
    sub_ae = models.build_autoencoder(**ae_kwargs).to(device)
    sub_unet = models.build_unet(**unet_kwargs).to(device)

    models.load_autoencoder_weights(whole_ae, args.whole_ae_ckpt, device)
    models.load_unet_weights(whole_unet, args.whole_unet_ckpt, device)
    models.load_autoencoder_weights(hemi_ae, args.hemi_ae_ckpt, device)
    models.load_unet_weights(hemi_unet, args.hemi_unet_ckpt, device)
    models.load_conditioner_weights(hemi_conditioner, args.hemi_unet_ckpt, device)
    models.load_autoencoder_weights(sub_ae, args.sub_ae_ckpt, device)
    models.load_unet_weights(sub_unet, args.sub_unet_ckpt, device)
    models.freeze(whole_ae, hemi_ae, hemi_unet, hemi_conditioner, sub_ae, sub_unet)
    return whole_ae, whole_unet, hemi_ae, hemi_unet, hemi_conditioner, sub_ae, sub_unet


def resolve_scale_factors(args, whole_ae, hemi_ae, sub_ae, train_loader, crop_masks, boxes, amp, device):
    """Latent scale factors: read from the LDM checkpoints, else estimated on one batch."""
    whole_sf = models.read_scale_factor(args.whole_unet_ckpt, ("whole_scale_factor", "scale_factor"))
    hemi_sf = models.read_scale_factor(args.hemi_unet_ckpt, ("hemi_scale_factor", "scale_factor"))
    sub_sf = models.read_scale_factor(args.sub_unet_ckpt, ("sub_scale_factor", "scale_factor"))
    if None in (whole_sf, hemi_sf, sub_sf):
        images = next(iter(train_loader))["image"].to(device)
        bg = float(args.bg_value)
        crops = {}
        for name in ("lhemi", "rhemi", "sub"):
            start, size = boxes[name]
            crops[name] = crop_padded(mask_background(images, crop_masks[name], bg), start, size, bg)
        if whole_sf is None:
            whole_sf = models.estimate_scale_factor(whole_ae, images, amp)
        if hemi_sf is None:
            hemi_sf = models.estimate_scale_factor(hemi_ae, torch.cat([crops["lhemi"], flip_lr(crops["rhemi"])]), amp)
        if sub_sf is None:
            sub_sf = models.estimate_scale_factor(sub_ae, crops["sub"], amp)
    return float(whole_sf), float(hemi_sf), float(sub_sf)


@torch.no_grad()
def validation_loss(unet, injector, val_loader, scheduler, n_batches, device, amp):
    unet.eval()
    total, count = 0.0, 0
    for i, batch in enumerate(val_loader):
        if i >= n_batches:
            break
        z0 = injector.encode(batch["image"].to(device))
        noise = torch.randn_like(z0)
        t = torch.randint(0, scheduler.num_train_timesteps, (z0.shape[0],), device=device)
        z_t = scheduler.add_noise(original_samples=z0, noise=noise, timesteps=t)
        with autocast(device_type="cuda", enabled=amp):
            eps = unet(z_t, timesteps=t)
        total += float(F.mse_loss(eps.float(), noise))
        count += 1
    unet.train()
    return total / max(1, count)


@torch.no_grad()
def save_samples(injector, args, step, outdir, device):
    sample_dir = Path(outdir) / "samples" / f"step{step:06d}"
    sample_dir.mkdir(parents=True, exist_ok=True)
    affine = np.diag([*parse_floats(args.spacing), 1.0])
    for i in range(int(args.sample_n)):
        generator = torch.Generator(device=device).manual_seed(int(args.seed) + i)
        x = generate(
            injector,
            ddim_steps=int(args.sample_ddim_steps),
            handoff_steps=int(args.sample_handoff_steps),
            part_t_ratio=float(args.sample_part_t_ratio),
            generator=generator,
        )
        nib.save(nib.Nifti1Image(x[0, 0].cpu().numpy().astype(np.float32), affine), str(sample_dir / f"sample_{i:02d}.nii.gz"))


def main():
    parser = build_parser("Compositional (assemble-then-refine) fine-tuning of the whole-brain LDM.", DEFAULTS)
    args = resolve(parser, DEFAULTS)
    rank, world_size, device = setup_distributed()
    seed_all(int(args.seed) + rank)
    amp = bool(args.torch_autocast) and device.type == "cuda"

    spacing, size = parse_floats(args.spacing), parse_ints(args.size)
    hemi_size, sub_size = parse_ints(args.hemi_size), parse_ints(args.sub_size)
    train_loader, val_loader, sampler = make_dataloaders(
        csv_path=args.csv,
        split_json_path=args.data_split_json_path,
        image_key=args.whole_key,
        spacing=spacing,
        size=size,
        batch_size=int(args.batch),
        num_workers=int(args.workers),
        distributed=world_size > 1,
        seed=int(args.seed),
    )
    crop_masks = load_template_masks(args.crop_template_dir, spacing, size, device)
    paste_masks = load_template_masks(args.paste_template_dir, spacing, size, device)

    whole_ae, whole_unet, hemi_ae, hemi_unet, hemi_conditioner, sub_ae, sub_unet = build_models(args, device)
    whole_sf, hemi_sf, sub_sf = resolve_scale_factors(
        args, whole_ae, hemi_ae, sub_ae, train_loader, crop_masks, part_boxes(spacing, size, hemi_size, sub_size), amp, device
    )
    experts = PartExperts(
        hemi_ae=hemi_ae,
        hemi_unet=hemi_unet,
        hemi_conditioner=hemi_conditioner,
        sub_ae=sub_ae,
        sub_unet=sub_unet,
        hemi_scale_factor=hemi_sf,
        sub_scale_factor=sub_sf,
        ddim_steps=int(args.part_ddim_steps),
        device=device,
        amp=amp,
    )
    injector = ScaffoldInjector(
        whole_ae=whole_ae,
        whole_unet=whole_unet,
        whole_scale_factor=whole_sf,
        experts=experts,
        crop_masks=crop_masks,
        paste_masks=paste_masks,
        spacing=spacing,
        whole_shape=size,
        hemi_shape=hemi_size,
        sub_shape=sub_size,
        part_t_ratio=float(args.part_t_ratio),
        cerebellum_erosion=int(args.cerebellum_erosion),
        feather_sigma=float(args.feather_sigma),
        tissue_margin=float(args.tissue_margin),
        bg_value=float(args.bg_value),
        device=device,
        amp=amp,
    )

    unet = whole_unet
    if world_size > 1:
        unet = DDP(whole_unet, device_ids=[device.index], broadcast_buffers=False)
    optimizer = torch.optim.AdamW(whole_unet.parameters(), lr=float(args.lr), weight_decay=float(args.weight_decay))
    scaler = torch.amp.GradScaler("cuda", enabled=amp)
    scheduler = models.build_ddpm_scheduler()
    abar = injector.abar

    global_step = 0
    if args.resume_ckpt:
        global_step, _ = models.load_checkpoint(args.resume_ckpt, whole_unet, device, optimizer, scaler)
    extra = {"scale_factor": whole_sf, "whole_scale_factor": whole_sf, "hemi_scale_factor": hemi_sf, "sub_scale_factor": sub_sf}
    if rank == 0:
        os.makedirs(args.outdir, exist_ok=True)
        with open(os.path.join(args.outdir, "args.json"), "w", encoding="utf-8") as f:
            json.dump(vars(args), f, indent=2, sort_keys=True)
        print(f"scale factors: whole={whole_sf:.4f} hemi={hemi_sf:.4f} sub={sub_sf:.4f}; resuming at step {global_step}")

    unet.train()
    steps_per_epoch = max(1, len(train_loader))
    epoch = global_step // steps_per_epoch
    if sampler is not None:
        sampler.set_epoch(epoch)
    data_iter = iter(train_loader)
    progress = tqdm(total=int(args.max_steps) - global_step, disable=rank != 0, ncols=120)
    log = []

    for step in range(global_step, int(args.max_steps)):
        try:
            batch = next(data_iter)
        except StopIteration:
            epoch += 1
            if sampler is not None:
                sampler.set_epoch(epoch)
            data_iter = iter(train_loader)
            batch = next(data_iter)
        images = batch["image"].to(device, non_blocking=True)
        with torch.no_grad():
            z0 = injector.encode(images)

        # Standard denoising objective.
        noise = torch.randn_like(z0)
        t = torch.randint(0, scheduler.num_train_timesteps, (z0.shape[0],), device=device)
        z_t = scheduler.add_noise(original_samples=z0, noise=noise, timesteps=t)
        with autocast(device_type="cuda", enabled=amp):
            eps = unet(z_t, timesteps=t)
        loss_std = F.mse_loss(eps.float(), noise)

        # Assemble-then-refine objective on the scaffold-injected latent.
        t_inj = broadcast_int(random.randint(int(args.t_inj_min), int(args.t_inj_max)), device)
        ab = abar[t_inj]
        with torch.no_grad():
            noise_inj = torch.randn_like(z0)
            z_tinj = ab.sqrt() * z0 + (1.0 - ab).sqrt() * noise_inj
            state = injector.handoff(z_tinj, t_inj)
            seam = injector.seam_band(state["m"], int(args.seam_width))
            eps_target = (state["z_inj"] - ab.sqrt() * z0) / (1.0 - ab).sqrt()
            weight = snr_weight(ab)
        t_batch = torch.full((z0.shape[0],), t_inj, device=device, dtype=torch.long)
        with autocast(device_type="cuda", enabled=amp):
            eps_inj = unet(state["z_inj"], timesteps=t_batch)
        residual = (eps_inj.float() - eps_target) * seam
        loss_seam = weight * residual.pow(2).sum() / (seam.sum() * z0.shape[1] + 1e-6)

        loss = loss_std + float(args.lambda_seam) * loss_seam
        lr_scale = min(1.0, (step + 1) / max(1, int(args.warmup_steps)))
        for group in optimizer.param_groups:
            group["lr"] = float(args.lr) * lr_scale
        optimizer.zero_grad(set_to_none=True)
        scaler.scale(loss).backward()
        scaler.unscale_(optimizer)
        torch.nn.utils.clip_grad_norm_(whole_unet.parameters(), float(args.grad_clip))
        scaler.step(optimizer)
        scaler.update()
        global_step = step + 1

        loss_value = mean_across_ranks(loss)
        std_value, seam_value = mean_across_ranks(loss_std), mean_across_ranks(loss_seam)
        if rank == 0:
            progress.set_description(f"step {global_step}/{int(args.max_steps)}")
            progress.set_postfix(loss=f"{loss_value:.4f}", std=f"{std_value:.4f}", seam=f"{seam_value:.4f}", t_inj=t_inj)
            progress.update(1)
            log.append({"step": global_step, "loss": loss_value, "loss_std": std_value, "loss_seam": seam_value})

            if args.val_every > 0 and global_step % int(args.val_every) == 0:
                val = validation_loss(whole_unet, injector, val_loader, scheduler, int(args.val_batches), device, amp)
                log[-1]["val_loss"] = val
                models.save_checkpoint(os.path.join(args.outdir, "UNET_last.pt"), whole_unet, optimizer, scaler, global_step, extra)
                with open(os.path.join(args.outdir, "train_log.json"), "w", encoding="utf-8") as f:
                    json.dump(log, f, indent=1)
            if args.ckpt_every > 0 and global_step % int(args.ckpt_every) == 0:
                models.save_checkpoint(
                    os.path.join(args.outdir, f"UNET_step{global_step:09d}.pt"), whole_unet, optimizer, scaler, global_step, extra
                )
            if args.sample_every > 0 and global_step % int(args.sample_every) == 0:
                whole_unet.eval()
                save_samples(injector, args, global_step, args.outdir, device)
                whole_unet.train()
        if dist.is_initialized():
            dist.barrier()

    if rank == 0:
        progress.close()
        models.save_checkpoint(os.path.join(args.outdir, "UNET_last.pt"), whole_unet, optimizer, scaler, global_step, extra)
    if dist.is_initialized():
        dist.destroy_process_group()


if __name__ == "__main__":
    main()
